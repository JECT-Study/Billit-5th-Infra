#!/usr/bin/env bash
# Nginx 설정 생성 (멱등). 인증서가 있으면 HTTPS 서버 블록을, 없으면 HTTP만 만든다.
#   운영 앱 VM: render-nginx.sh edge   (환경: /srv/ject/app/edge.env)
#   개발 VM:   render-nginx.sh dev-gateway
# edge.env 변수: PROD_DOMAIN(선택), DEV_DOMAIN(선택), DEV_UPSTREAM(개발 VM 사설IP:8080)
set -euo pipefail
MODE="${1:?edge|dev-gateway}"
SRC_DIR="$(cd "$(dirname "$0")/.." && pwd)"

proxy_common='
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Request-Id $request_id;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection $connection_upgrade;
        proxy_read_timeout 60s;'

# 관리·관측 엔드포인트는 공개 경로로 연결하지 않는다.
deny_internal='
    if ($request_uri ~ ";") { return 400; }
    location ~* ^/(actuator|metrics|prometheus|swagger-ui|v3/api-docs) { return 404; }'

app_locations() {   # $1 = be upstream, $2 = fe upstream(비우면 be가 전부 처리)
  local be="$1" fe="${2:-}"
  cat <<EOF
$deny_internal
    location = /readyz {
        set \$be_up $be;
        proxy_pass http://\$be_up/readyz;$proxy_common
    }
    location /api/ {
        set \$be_up $be;
        proxy_pass http://\$be_up;$proxy_common
    }
    location / {
        set \$web_up ${fe:-$be};
        proxy_pass http://\$web_up;$proxy_common
    }
EOF
}

tls_block() {   # $1 = cert name
  cat <<EOF
    ssl_certificate     /etc/letsencrypt/live/$1/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$1/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_session_cache shared:SSL:5m;
    ssl_session_timeout 1d;
    add_header Strict-Transport-Security "max-age=31536000" always;
EOF
}

common_headers='
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy strict-origin-when-cross-origin always;'

# 새 설정으로 교체한 뒤 실행 중인 Nginx로 문법 검사. 실패하면 이전 파일로 되돌리고 실패 처리.
swap_and_test() {   # file container
  local f="$1" c="$2"
  if [ -f "$f" ]; then cp -p "$f" "$f.bak"; fi
  mv "$f.new" "$f"
  if docker ps --format '{{.Names}}' | grep -qx "$c"; then
    if ! docker exec "$c" nginx -t -q; then
      if [ -f "$f.bak" ]; then mv "$f.bak" "$f"; else rm -f "$f"; fi
      echo "nginx -t 실패: 이전 설정으로 되돌림" >&2; exit 1
    fi
  fi
  rm -f "$f.bak"
}

case "$MODE" in
edge)
  ENV_FILE=/srv/ject/app/edge.env
  [ -f "$ENV_FILE" ] && . "$ENV_FILE"
  PROD_DOMAIN="${PROD_DOMAIN:-}"; DEV_DOMAIN="${DEV_DOMAIN:-}"; DEV_UPSTREAM="${DEV_UPSTREAM:-}"
  CERT_NAME="${CERT_NAME:-ject}"
  OUT=/srv/ject/app/nginx
  install -d "$OUT/conf.d"
  install -m 0644 "$SRC_DIR/nginx/nginx.conf" "$OUT/nginx.conf"
  have_cert=0
  [ -n "$PROD_DOMAIN" ] && [ -s "/srv/ject/certs/live/$CERT_NAME/fullchain.pem" ] && have_cert=1
  {
    echo "# generated by render-nginx.sh edge — 직접 수정하지 말 것"
    # 기본 서버: ACME 응답, 헬스, 그 외 도메인 없는 요청
    cat <<EOF
server {
    listen 80 default_server;
    server_name _;
$common_headers
    location /.well-known/acme-challenge/ { root /var/www/acme; }
    location = /nginx-health { access_log off; return 200 "ok\n"; }
EOF
    if [ "$have_cert" = 1 ]; then
      echo '    location / { return 301 https://$host$request_uri; }'
    else
      # 도메인·인증서 준비 전: IP로 운영 앱 동작을 확인할 수 있게 HTTP로 프록시한다.
      app_locations "be:8080" ""
    fi
    echo "}"
    if [ "$have_cert" = 1 ]; then
      cat <<EOF
server {
    listen 443 ssl;
    http2 on;
    server_name $PROD_DOMAIN;
$(tls_block "$CERT_NAME")
$common_headers
$(app_locations "be:8080" "${PROD_FE_UPSTREAM:-}")
}
EOF
      if [ -n "$DEV_DOMAIN" ] && [ -n "$DEV_UPSTREAM" ]; then
        cat <<EOF
server {
    listen 443 ssl;
    http2 on;
    server_name $DEV_DOMAIN;
$(tls_block "$CERT_NAME")
$common_headers
    add_header X-Robots-Tag "noindex, nofollow" always;
    location / {
        proxy_pass http://$DEV_UPSTREAM;$proxy_common
    }
}
EOF
      fi
      # 알 수 없는 호스트로 들어온 HTTPS 요청은 끊는다.
      cat <<EOF
server {
    listen 443 ssl default_server;
    server_name _;
$(tls_block "$CERT_NAME")
    return 444;
}
EOF
    fi
  } > "$OUT/conf.d/ject.conf.new"
  swap_and_test "$OUT/conf.d/ject.conf" ject-edge-nginx-1
  echo "rendered edge (https=$have_cert prod=${PROD_DOMAIN:-none} dev=${DEV_DOMAIN:-none})"
  ;;
dev-gateway)
  OUT=/srv/ject/dev/nginx
  install -d "$OUT/conf.d"
  install -m 0644 "$SRC_DIR/nginx/nginx.conf" "$OUT/nginx.conf"
  {
    echo "# generated by render-nginx.sh dev-gateway — 직접 수정하지 말 것"
    cat <<EOF
server {
    listen 8080 default_server;
    server_name _;
$common_headers
    location = /nginx-health { access_log off; return 200 "ok\n"; }
$(app_locations "be:8080" "${DEV_FE_UPSTREAM:-}")
}
EOF
  } > "$OUT/conf.d/dev.conf.new"
  swap_and_test "$OUT/conf.d/dev.conf" ject-dev-gateway-nginx-1
  echo "rendered dev-gateway"
  ;;
*) echo "unknown mode $MODE" >&2; exit 2 ;;
esac
